package com.bansify.ai.core.designsystem

import androidx.compose.ui.unit.dp

/**
 * Spacing scale strictly limited to: 4 · 8 · 12 · 16 · 24 · 32
 */
object Space {
    val xxs = 4.dp
    val xs = 8.dp
    val sm = 12.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
}

/**
 * Motion duration tokens (milliseconds): 150ms micro, 220ms screen.
 */
object Motion {
    const val Micro = 150
    const val Screen = 220
}
